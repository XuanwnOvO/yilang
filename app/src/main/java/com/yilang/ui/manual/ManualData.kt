package com.yilang.ui.manual

/** 手册内容块：段落 / 代码示例（lang = yl 或 cpp）/ 小贴士 */
sealed interface Block {
    data class Para(val text: String) : Block
    data class Code(val code: String, val lang: String = "yl") : Block
    data class Tip(val text: String) : Block
}

/** 手册章节页 */
data class ManualPage(
    val id: String,
    val title: String,
    val subtitle: String,
    val blocks: List<Block>,
)

